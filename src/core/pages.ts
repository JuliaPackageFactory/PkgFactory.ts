/** Documenter.jl's deploydocs writes the root redirect to the deployed version
 * only when index.html is missing or starts with this comment
 * (`HTMLWriter.generate_redirect_file`). */
export const documenterRedirectComment = '<!--This file is automatically generated by Documenter.jl-->';
/** Initial tree of the orphan `gh-pages` branch. It holds no package sources, so
 * GitHub Pages never publishes them, and it serves a placeholder instead of a
 * 404 until the Documentation job deploys. The placeholder starts with
 * Documenter's comment so the first deployment replaces it with its redirect. */
export function pagesPlaceholder(repository: string): Record<string, string> {
  const url = `https://github.com/${repository}`;
  const name = repository.slice(repository.indexOf('/') + 1);
  return {
    '.nojekyll': 'GitHub Pages serves this branch as is, without Jekyll, while this file exists.\n',
    'index.html': `${documenterRedirectComment}
<!-- PkgFactory placeholder. Documenter.jl replaces this page on its first deployment because it starts with the comment above. -->
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>${name} documentation</title>
</head>
<body>
<h1>${name}</h1>
<p>The documentation has not been deployed yet. The Documentation job in <a href="${url}/actions/workflows/CI.yml">GitHub Actions</a> builds it, and GitHub Pages publishes it shortly after that job finishes. If the job failed, its log shows why.</p>
<p>Reload this page once both have finished. The source code is at <a href="${url}">${url}</a>.</p>
</body>
</html>
`,
  };
}
