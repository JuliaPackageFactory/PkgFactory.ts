import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mcpHttp } from '../packages/pkgfactory/src/mcp/server.js';
import { Factory } from '../packages/pkgfactory/src/application/engine.js';
import { FakeGitHub } from './fake-github.js';
test('Streamable HTTP negotiates, lists tools, previews and creates with request cancellation', async () => {
  const remote = new FakeGitHub(); const factory = new Factory({fetcher: remote.fetch});
  const credentials = {subject: '42', token: 'secret'};
  const call = async (method: string, params: unknown, signal?: AbortSignal) => {
    const response = await mcpHttp(new Request('https://pkgfactory.test/mcp', {method: 'POST', signal, headers: {'Content-Type': 'application/json', Accept: 'application/json, text/event-stream', 'MCP-Protocol-Version': '2025-11-25'}, body: JSON.stringify({jsonrpc: '2.0', id: crypto.randomUUID(), method, params})}), factory, credentials);
    assert.equal(response.status, 200); return await response.json() as any;
  };
  const initialized = await call('initialize', {protocolVersion: '2025-11-25', capabilities: {}, clientInfo: {name: 'test', version: '1'}});
  assert.equal(initialized.result.serverInfo.name, 'PkgFactory');
  assert.deepEqual((await call('tools/list', {})).result.tools.map((t: any) => t.name).sort(), ['create_package', 'list_templates', 'preview_package']);
  const denied = await call('tools/call', {name: 'preview_package', arguments: {owner: 'unowned', name: 'Foreign', authors: ['Tester']}});
  assert.equal(denied.result.isError, true);
  const preview = await call('tools/call', {name: 'preview_package', arguments: {owner: 'tester', name: 'Remote', authors: ['Tester'], template: 'minimum'}});
  const plan = JSON.parse(preview.result.content[0].text);
  const reference = {id: plan.id, uuid: plan.uuid, createdAt: plan.createdAt};
  const unconfirmed = await call('tools/call', {name: 'create_package', arguments: {...plan.spec, plan: reference}});
  assert.ok(unconfirmed.error || unconfirmed.result.isError, 'confirm: true is required');
  assert.deepEqual(remote.calls.filter(c => c.method !== 'GET'), []);
  const result = await call('tools/call', {name: 'create_package', arguments: {...plan.spec, plan: reference, confirm: true}});
  assert.equal(JSON.parse(result.result.content[0].text).state, 'complete');
  assert.equal(remote.files['Project.toml'], plan.files['Project.toml']);
  const again = await call('tools/call', {name: 'create_package', arguments: {...plan.spec, plan: reference, confirm: true}});
  assert.equal(again.result.isError, true); assert.match(again.result.content[0].text, /already exists/);
  const plan2 = await factory.preview({owner: 'tester', name: 'Cancelled', authors: ['Tester']});
  const abort = new AbortController(); abort.abort();
  const before = remote.calls.length;
  await assert.rejects(factory.execute(plan2, credentials, abort.signal)); assert.equal(remote.calls.length, before);
});
